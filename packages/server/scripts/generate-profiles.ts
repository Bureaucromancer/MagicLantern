/**
 * Writes packages/server/src/engine/profiles/builtin.generated.ts from the
 * repository's profiles/*.json, so the built-in profiles compile into `dist`
 * and ship with the daemon. The JSON is the source; edit it, then run
 *
 *     node packages/server/scripts/generate-profiles.ts
 *
 * from the repository root (Node strips the types). `--check` writes nothing
 * and exits 1 when the module is stale. A server test also compares the
 * module with the JSON, so a forgotten run fails `pnpm test`.
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import * as prettier from 'prettier';

const profilesDir = new URL('../../../profiles/', import.meta.url);
const output = new URL('../src/engine/profiles/builtin.generated.ts', import.meta.url);

const HEADER = `// SPDX-License-Identifier: MIT
// Copyright (C) 2026 Magic Lantern contributors

// Generated by packages/server/scripts/generate-profiles.ts from profiles/*.json.
// Do not edit: change the JSON and run the script.
`;

async function render(): Promise<string> {
  const files = readdirSync(profilesDir)
    .filter((name) => name.endsWith('.json'))
    .sort();
  const data: unknown[] = files.map(
    (name) => JSON.parse(readFileSync(new URL(name, profilesDir), 'utf8')) as unknown,
  );
  const source =
    `${HEADER}\n` +
    '/** The built-in profiles as parsed JSON, in file-name order. The loader validates them. */\n' +
    `export const BUILTIN_PROFILE_DATA: readonly unknown[] = ${JSON.stringify(data)};\n`;
  const path = fileURLToPath(output);
  const options = (await prettier.resolveConfig(path)) ?? {};
  return prettier.format(source, { ...options, filepath: path });
}

async function main(): Promise<number> {
  const text = await render();
  const path = fileURLToPath(output);
  const previous = existsSync(output) ? readFileSync(output, 'utf8') : null;
  if (previous === text) {
    console.log(`${path} is current.`);
    return 0;
  }
  if (process.argv.includes('--check')) {
    console.error(`${path} is stale: run node packages/server/scripts/generate-profiles.ts.`);
    return 1;
  }
  writeFileSync(output, text);
  console.log(`Wrote ${path}.`);
  return 0;
}

process.exitCode = await main();
